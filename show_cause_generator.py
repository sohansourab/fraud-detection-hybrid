'''The Investigator Agent (agent_investigate.py) acts as the "Legal Officer" or "Bureaucrat" of your system.
While the Root Agent (Scanner) acts like the Police (finding the crime),
 the Investigator acts like the Court Clerk (issuing the paperwork).'''

import json
import os
from fpdf import FPDF

# --- CONFIGURATION ---
INPUT_FILE = "output/reports/fraud_report.json"
NOTICE_DIR = "output/notices"

# --- PDF GENERATOR ---
class PDFNotice(FPDF):
    def header(self):
        self.set_font('Arial', 'B', 12)
        self.cell(0, 10, 'GOVERNMENT OF INDIA - FRAUD DETECTION UNIT', 0, 1, 'C')
        self.ln(5)
        self.line(10, 25, 200, 25)

def create_show_cause_notice(case_data):
    pdf = PDFNotice()
    pdf.add_page()
    
    ben_id = case_data.get('ID', 'UNKNOWN')
    verdict = case_data.get('Verdict', 'SUSPICIOUS')
    
    pdf.set_font("Arial", 'B', 14)
    pdf.cell(0, 10, f"SHOW CAUSE NOTICE: {ben_id}", 0, 1, 'C')
    pdf.ln(10)
    
    pdf.set_font("Arial", size=11)
    text = f"""
    To the Beneficiary (ID: {ben_id}),
    
    SUBJECT: DETECTION OF IRREGULARITIES ({verdict})
    
    Our Root Agent system has flagged your account during a routine audit.
    
    VIOLATION DETAILS:
    - The mobile number associated with your account is linked to suspicious patterns.
    - Violation Type: {verdict}
    
    ACTION REQUIRED:
    You are required to submit proof of identity and address to the Block Development Officer (BDO) within 7 days. Failure to comply will result in immediate suspension of benefits.
    
    Generated by: Root Agent (AI-420)
    """
    pdf.multi_cell(0, 7, text)
    
    filename = os.path.join(NOTICE_DIR, f"Notice_{ben_id}.pdf")
    pdf.output(filename)
    print(f"   📄 Generated Notice for {ben_id}")

# --- EXECUTION ---
if __name__ == "__main__":
    if not os.path.exists(INPUT_FILE):
        print(f"❌ {INPUT_FILE} missing. Run agent_root.py first!")
    else:
        with open(INPUT_FILE, 'r') as f:
            reports = json.load(f)
            
        print(f"📂 Investigator reading {len(reports)} case files...")
        
        fraud_count = 0
        for case in reports:
            # Check if Verdict contains "FRAUD" or "SUSPICIOUS" (Case insensitive)
            verdict = str(case.get('Verdict', '')).upper()
            if "FRAUD" in verdict or "SUSPICIOUS" in verdict:
                create_show_cause_notice(case)
                fraud_count += 1
                
        print(f"\n🚨 Investigation Complete. {fraud_count} Legal Notices generated.")

