def sanitize_text(text):
    """Convert Unicode characters to ASCII-compatible equivalents."""
    if not isinstance(text, str):
        text = str(text)
    
    replacements = {
        '\u2019': "'",   # Right single quote
        '\u2018': "'",   # Left single quote
        '\u201c': '"',   # Left double quote
        '\u201d': '"',   # Right double quote
        '\u2013': '-',   # En dash
        '\u2014': '--',  # Em dash
        '\u2022': '-',   # Bullet
        '\u2026': '...', # Ellipsis
        '\u00a0': ' ',   # Non-breaking space
        '\u00b0': ' deg', # Degree symbol
        '\u20b9': 'Rs.',  # Indian Rupee symbol
    }
    
    for unicode_char, ascii_char in replacements.items():
        text = text.replace(unicode_char, ascii_char)
    
    text = text.encode('latin-1', errors='replace').decode('latin-1')
    return text


class PDFNotice(FPDF):
    """Custom PDF class with header and footer."""
    
    def __init__(self, ministry="Ministry of Rural Development"):
        super().__init__()
        self.ministry = ministry
    
    def header(self):
        self.set_font('Arial', 'B', 12)
        self.cell(0, 10, 'GOVERNMENT OF INDIA - FRAUD DETECTION UNIT', 0, 1, 'C')
        self.set_font('Arial', 'I', 9)
        self.cell(0, 5, self.ministry, 0, 1, 'C')
        self.ln(3)
        self.line(10, 28, 200, 28)
        
    def footer(self):
        self.set_y(-15)
        self.set_font('Arial', 'I', 8)
        self.cell(0, 10, f'Page {self.page_no()} | Generated by Multi-Domain Fraud Scanner', 0, 0, 'C')


def format_violations(flags):
    """Format violation flags into readable text."""
    violations = []
    for i, flag in enumerate(flags, 1):
        rule_id = sanitize_text(flag.get('rule_id', ''))
        rule_name = sanitize_text(flag.get('name', 'Unknown Rule'))
        pattern = sanitize_text(flag.get('pattern', ''))
        description = sanitize_text(flag.get('description', ''))
        evidence = flag.get('evidence', {})
        
        violation_text = f"{i}. [{rule_id}] {rule_name} ({pattern})\n"
        violation_text += f"   Description: {description}\n"
        
        if evidence:
            evidence_items = []
            for key, value in evidence.items():
                formatted_key = sanitize_text(key.replace('_', ' ').title())
                formatted_value = sanitize_text(str(value))
                evidence_items.append(f"{formatted_key}: {formatted_value}")
            violation_text += f"   Evidence: {', '.join(evidence_items)}\n"
        
        violations.append(violation_text)
    
    return "\n".join(violations)


def get_risk_level(score):
    """Determine risk level from score."""
    if score <= 25:
        return "LOW"
    elif score <= 50:
        return "MEDIUM"
    elif score <= 75:
        return "HIGH"
    else:
        return "CRITICAL"


def get_risk_color(risk_level):
    """Get fill color based on risk level."""
    colors = {
        "LOW": (255, 255, 200),      # Light yellow
        "MEDIUM": (255, 230, 200),   # Light orange
        "HIGH": (255, 200, 200),     # Light red
        "CRITICAL": (255, 150, 150)  # Darker red
    }
    return colors.get(risk_level, (255, 255, 200))


def create_show_cause_notice(case_data):
    """Generate PDF notice for a flagged record (any domain)."""
    
    # Extract data from new JSON structure
    record_id = sanitize_text(case_data.get('record_id', 'UNKNOWN'))
    record_name = sanitize_text(case_data.get('record_name', 'Unknown'))
    domain = case_data.get('domain', 'Civil Registry')
    flags = case_data.get('flags', [])
    total_risk_score = case_data.get('total_risk_score', 0)
    risk_level = get_risk_level(total_risk_score)
    
    # Get domain-specific config
    config = DOMAIN_CONFIG.get(domain, DOMAIN_CONFIG["Civil Registry"])
    
    # Create PDF with domain-specific ministry
    pdf = PDFNotice(ministry=config['ministry'])
    pdf.add_page()
    
    # Get violation types
    violation_types = [sanitize_text(f.get('name', 'Unknown')) for f in flags]
    
    # Notice Reference Number (domain-prefixed)
    domain_prefix = {
        "Civil Registry": "CR",
        "MGNREGA Labor": "MGN",
        "PM-JAY Medical": "PMJ"
    }.get(domain, "GEN")
    ref_no = f"SCN/{domain_prefix}/{datetime.now().strftime('%Y%m%d')}/{record_id}"
    
    # Title
    pdf.set_font("Arial", 'B', 14)
    pdf.cell(0, 10, "SHOW CAUSE NOTICE", 0, 1, 'C')
    pdf.set_font("Arial", 'B', 11)
    pdf.cell(0, 7, f"Reference: {ref_no}", 0, 1, 'C')
    pdf.ln(5)
    
    # Date
    pdf.set_font("Arial", size=10)
    pdf.cell(0, 5, f"Date: {datetime.now().strftime('%d %B %Y')}", 0, 1, 'R')
    pdf.ln(5)
    
    # Domain Badge
    pdf.set_fill_color(200, 220, 255)
    pdf.set_font("Arial", 'B', 10)
    pdf.cell(0, 7, f"  DOMAIN: {domain}", 0, 1, 'L', True)
    pdf.ln(3)
    
    # Recipient Details
    pdf.set_font("Arial", 'B', 11)
    pdf.cell(0, 7, "TO:", 0, 1)
    pdf.set_font("Arial", size=11)
    pdf.cell(0, 6, f"Record ID: {record_id}", 0, 1)
    pdf.cell(0, 6, f"Details: {record_name}", 0, 1)
    pdf.ln(5)
    
    # Subject Line
    pdf.set_font("Arial", 'B', 11)
    subject_text = sanitize_text(f"SUBJECT: Detection of Irregularities - {', '.join(violation_types[:3])}")
    if len(violation_types) > 3:
        subject_text += f" (+{len(violation_types) - 3} more)"
    pdf.multi_cell(0, 7, subject_text)
    pdf.ln(3)
    
    # Risk Assessment Box
    risk_color = get_risk_color(risk_level)
    pdf.set_fill_color(*risk_color)
    pdf.set_font("Arial", 'B', 10)
    pdf.cell(0, 8, f"  RISK ASSESSMENT: {risk_level} (Score: {total_risk_score})", 0, 1, 'L', True)
    pdf.ln(5)
    
    # Body Text
    pdf.set_font("Arial", size=10)
    intro_text = sanitize_text(
        "Dear Sir/Madam,\n\n"
        "This notice is being issued pursuant to the findings of an automated audit "
        "conducted by the Multi-Domain Fraud Detection System under the Digital India Initiative.\n\n"
        f"During a routine scan of records in the {config['db_name']}, "
        f"the following record (ID: {record_id}) has been flagged for irregularities:"
    )
    pdf.multi_cell(0, 6, intro_text)
    pdf.ln(3)
    
    # Violations Section
    pdf.set_font("Arial", 'B', 11)
    pdf.cell(0, 7, "DETECTED VIOLATIONS:", 0, 1)
    pdf.set_font("Arial", size=10)
    
    violations_text = format_violations(flags)
    pdf.multi_cell(0, 5, violations_text)
    pdf.ln(3)
    
    # Action Required
    pdf.set_font("Arial", 'B', 11)
    pdf.cell(0, 7, "ACTION REQUIRED:", 0, 1)
    pdf.set_font("Arial", size=10)
    
    # Build document list
    docs_list = "\n".join([f"   - {doc}" for doc in config['docs_required']])
    
    action_text = sanitize_text(
        f"You are hereby directed to:\n\n"
        f"1. Appear before the {config['authority']} within 7 (seven) working "
        f"days from the date of receipt of this notice.\n\n"
        f"2. Submit the following documents for verification:\n{docs_list}\n\n"
        f"3. Provide a written explanation for the irregularities detected.\n\n"
        f"FAILURE TO COMPLY with this notice within the stipulated time period will result in:\n"
        f"- Immediate suspension of all benefits/claims\n"
        f"- Initiation of recovery proceedings for any amounts wrongfully claimed\n"
        f"- Referral to appropriate law enforcement authorities"
    )
    pdf.multi_cell(0, 5, action_text)
    pdf.ln(5)
    
    # Signature Block
    pdf.set_font("Arial", 'B', 10)
    pdf.cell(0, 6, "Issued by Authority:", 0, 1)
    pdf.set_font("Arial", size=10)
    pdf.cell(0, 5, "Multi-Domain Fraud Detection System", 0, 1)
    pdf.cell(0, 5, config['ministry'], 0, 1)
    pdf.cell(0, 5, "Government of India", 0, 1)
    
    # Create domain-specific subdirectory
    domain_dir = domain.replace(" ", "_").lower()
    output_dir = os.path.join(NOTICE_DIR, domain_dir)
    os.makedirs(output_dir, exist_ok=True)
    
    # Save PDF
    filename = os.path.join(output_dir, f"Notice_{record_id}.pdf")
    pdf.output(filename)
    
    return filename, risk_level


# --- EXECUTION ---
def main():
    """Main execution function."""
    os.makedirs(NOTICE_DIR, exist_ok=True)
    
    if not os.path.exists(INPUT_FILE):
        print(f"[ERROR] {INPUT_FILE} missing. Run audit_scanner.py first!")
        return
    
    with open(INPUT_FILE, 'r') as f:
        report = json.load(f)
    
    # Extract flagged records from new structure
    flagged = report.get('flagged_records', [])
    summary = report.get('summary', {})
    metadata = report.get('scan_metadata', {})
    
    print("\n" + "="*70)
    print("  SHOW CAUSE NOTICE GENERATOR - MULTI-DOMAIN")
    print("="*70)
    print(f"  Input: {INPUT_FILE}")
    print(f"  Scan Timestamp: {metadata.get('scan_timestamp', 'N/A')}")
    print(f"  Domains: {', '.join(metadata.get('domains_scanned', []))}")
    print(f"  Total Flagged Records: {len(flagged)}")
    print("="*70 + "\n")
    
    # Track statistics
    notice_count = 0
    domain_counts = {}
    risk_counts = {"LOW": 0, "MEDIUM": 0, "HIGH": 0, "CRITICAL": 0}
    
    for case in flagged:
        if case.get('flags'):
            filename, risk_level = create_show_cause_notice(case)
            notice_count += 1
            
            # Track by domain
            domain = case.get('domain', 'Unknown')
            domain_counts[domain] = domain_counts.get(domain, 0) + 1
            
            # Track by risk
            risk_counts[risk_level] += 1
            
            # Print progress every 100 notices
            if notice_count % 100 == 0:
                print(f"   [PROGRESS] Generated {notice_count} notices...")
    
    # Final report
    print("\n" + "="*70)
    print("  NOTICE GENERATION COMPLETE")
    print("="*70)
    print(f"\n  Total Notices Generated: {notice_count}")
    
    print(f"\n  [BY DOMAIN]")
    for domain, count in sorted(domain_counts.items()):
        print(f"    * {domain}: {count}")
    
    print(f"\n  [BY RISK LEVEL]")
    for level, count in risk_counts.items():
        if count > 0:
            print(f"    * {level}: {count}")
    
    print(f"\n  Output Directory: {NOTICE_DIR}/")
    print(f"    - {NOTICE_DIR}/civil_registry/")
    print(f"    - {NOTICE_DIR}/mgnrega_labor/")
    print(f"    - {NOTICE_DIR}/pm-jay_medical/")
    print("="*70 + "\n")


if __name__ == "__main__":
    main()
