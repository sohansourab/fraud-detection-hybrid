if __name__ == "__main__":
    os.makedirs(NOTICE_DIR, exist_ok=True)
    
    if not os.path.exists(INPUT_FILE):
        print(f"[ERROR] {INPUT_FILE} missing. Run audit_scanner.py first!")
    else:
        with open(INPUT_FILE, 'r') as f:
            report = json.load(f)
        
        # Extract flagged beneficiaries from new structure
        flagged = report.get('flagged_beneficiaries', [])
        summary = report.get('summary', {})
        
        print(f"\n{'='*60}")
        print("SHOW CAUSE NOTICE GENERATOR")
        print(f"{'='*60}")
        print(f"Reading fraud report: {INPUT_FILE}")
        print(f"Total flagged cases: {len(flagged)}")
        print(f"{'='*60}\n")
        
        notice_count = 0
        risk_counts = {"LOW": 0, "MEDIUM": 0, "HIGH": 0, "CRITICAL": 0}
        
        for case in flagged:
            # Generate notice for all flagged beneficiaries
            if case.get('flags'):
                create_show_cause_notice(case)
                notice_count += 1
                risk_level = get_risk_level(case.get('total_risk_score', 0))
                risk_counts[risk_level] += 1
        
        print(f"\n{'='*60}")
        print("INVESTIGATION COMPLETE")
        print(f"{'='*60}")
        print(f"Total Notices Generated: {notice_count}")
        print(f"\nBy Risk Level:")
        for level, count in risk_counts.items():
            if count > 0:
                print(f"   * {level}: {count}")
        print(f"\nOutput Directory: {NOTICE_DIR}")
        print(f"{'='*60}")