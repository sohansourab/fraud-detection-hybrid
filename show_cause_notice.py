# --- CONFIGURATION ---
INPUT_FILE = "output/reports/fraud_report.json"
NOTICE_DIR = "output/notices"


def sanitize_text(text):
    """Convert Unicode characters to ASCII-compatible equivalents."""
    if not isinstance(text, str):
        text = str(text)
    
    # Common Unicode replacements
    replacements = {
        '\u2019': "'",   # Right single quote
        '\u2018': "'",   # Left single quote
        '\u201c': '"',   # Left double quote
        '\u201d': '"',   # Right double quote
        '\u2013': '-',   # En dash
        '\u2014': '--',  # Em dash
        '\u2022': '-',   # Bullet
        '\u2026': '...', # Ellipsis
        '\u00a0': ' ',   # Non-breaking space
        '\u00b0': ' deg', # Degree symbol
        '\u20b9': 'Rs.',  # Indian Rupee symbol
    }
    
    for unicode_char, ascii_char in replacements.items():
        text = text.replace(unicode_char, ascii_char)
    
    # Remove any remaining non-latin1 characters
    text = text.encode('latin-1', errors='replace').decode('latin-1')
    
    return text


# --- PDF GENERATOR ---
class PDFNotice(FPDF):
    def header(self):
        self.set_font('Arial', 'B', 12)
        self.cell(0, 10, 'GOVERNMENT OF INDIA - FRAUD DETECTION UNIT', 0, 1, 'C')
        self.set_font('Arial', 'I', 9)
        self.cell(0, 5, 'Ministry of Rural Development | MGNREGA Audit Division', 0, 1, 'C')
        self.ln(3)
        self.line(10, 28, 200, 28)
        
    def footer(self):
        self.set_y(-15)
        self.set_font('Arial', 'I', 8)
        self.cell(0, 10, f'Page {self.page_no()} | Generated by Root Agent (AI-420)', 0, 0, 'C')


def format_violations(flags):
    """Format violation flags into readable text."""
    violations = []
    for i, flag in enumerate(flags, 1):
        rule_name = sanitize_text(flag.get('name', 'Unknown Rule'))
        pattern = sanitize_text(flag.get('pattern', ''))
        description = sanitize_text(flag.get('description', ''))
        evidence = flag.get('evidence', {})
        
        # Use ASCII-compatible bullet/numbering
        violation_text = f"{i}. {rule_name} ({pattern})\n"
        violation_text += f"   Description: {description}\n"
        
        # Format evidence
        if evidence:
            evidence_items = []
            for key, value in evidence.items():
                formatted_key = sanitize_text(key.replace('_', ' ').title())
                formatted_value = sanitize_text(str(value))
                evidence_items.append(f"{formatted_key}: {formatted_value}")
            violation_text += f"   Evidence: {', '.join(evidence_items)}\n"
        
        violations.append(violation_text)
    
    return "\n".join(violations)


def get_risk_level(score):
    """Determine risk level from score."""
    if score <= 25:
        return "LOW"
    elif score <= 50:
        return "MEDIUM"
    elif score <= 75:
        return "HIGH"
    else:
        return "CRITICAL"


def create_show_cause_notice(case_data):
    """Generate PDF notice for a flagged beneficiary."""
    pdf = PDFNotice()
    pdf.add_page()
    
    # Extract and sanitize data from JSON structure
    ben_id = sanitize_text(case_data.get('beneficiary_id', 'UNKNOWN'))
    name = sanitize_text(case_data.get('name', 'Unknown'))
    flags = case_data.get('flags', [])
    total_risk_score = case_data.get('total_risk_score', 0)
    risk_level = get_risk_level(total_risk_score)
    
    # Get violation types
    violation_types = [sanitize_text(f.get('name', 'Unknown')) for f in flags]
    
    # Notice Reference Number
    ref_no = f"SCN/{datetime.now().strftime('%Y%m%d')}/{ben_id}"
    
    # Title
    pdf.set_font("Arial", 'B', 14)
    pdf.cell(0, 10, "SHOW CAUSE NOTICE", 0, 1, 'C')
    pdf.set_font("Arial", 'B', 11)
    pdf.cell(0, 7, f"Reference: {ref_no}", 0, 1, 'C')
    pdf.ln(5)
    
    # Date
    pdf.set_font("Arial", size=10)
    pdf.cell(0, 5, f"Date: {datetime.now().strftime('%d %B %Y')}", 0, 1, 'R')
    pdf.ln(5)
    
    # Recipient Details
    pdf.set_font("Arial", 'B', 11)
    pdf.cell(0, 7, "TO:", 0, 1)
    pdf.set_font("Arial", size=11)
    pdf.cell(0, 6, f"Beneficiary Name: {name}", 0, 1)
    pdf.cell(0, 6, f"Beneficiary ID: {ben_id}", 0, 1)
    pdf.ln(5)
    
    # Subject Line
    pdf.set_font("Arial", 'B', 11)
    subject_text = sanitize_text(f"SUBJECT: Detection of Irregularities in Beneficiary Records - {', '.join(violation_types)}")
    pdf.multi_cell(0, 7, subject_text)
    pdf.ln(3)
    
    # Risk Assessment Box
    if risk_level in ['HIGH', 'CRITICAL']:
        pdf.set_fill_color(255, 230, 230)
    else:
        pdf.set_fill_color(255, 255, 200)
    pdf.set_font("Arial", 'B', 10)
    pdf.cell(0, 8, f"  RISK ASSESSMENT: {risk_level} (Score: {total_risk_score})", 0, 1, 'L', True)
    pdf.ln(5)
    
    # Body Text
    pdf.set_font("Arial", size=10)
    intro_text = sanitize_text(
        "Dear Sir/Madam,\n\n"
        "This notice is being issued pursuant to the findings of an automated audit "
        "conducted by the Root Agent Fraud Detection System under the Digital India Initiative.\n\n"
        f"During a routine scan of beneficiary records in the Civil Registry database, "
        f"your account (ID: {ben_id}) has been flagged for the following irregularities:"
    )
    
    pdf.multi_cell(0, 6, intro_text)
    pdf.ln(3)
    
    # Violations Section
    pdf.set_font("Arial", 'B', 11)
    pdf.cell(0, 7, "DETECTED VIOLATIONS:", 0, 1)
    pdf.set_font("Arial", size=10)
    
    violations_text = format_violations(flags)
    pdf.multi_cell(0, 5, violations_text)
    pdf.ln(3)
    
    # Action Required
    pdf.set_font("Arial", 'B', 11)
    pdf.cell(0, 7, "ACTION REQUIRED:", 0, 1)
    pdf.set_font("Arial", size=10)
    
    action_text = sanitize_text(
        "You are hereby directed to:\n\n"
        "1. Appear before the Block Development Officer (BDO) within 7 (seven) working "
        "days from the date of receipt of this notice.\n\n"
        "2. Submit the following documents for verification:\n"
        "   - Original Aadhaar Card\n"
        "   - Proof of Address (Utility Bill/Bank Statement)\n"
        "   - Job Card (if applicable)\n"
        "   - Family Ration Card\n"
        "   - Age Proof Certificate (Birth Certificate/School Certificate)\n\n"
        "3. Provide a written explanation for the irregularities detected.\n\n"
        "FAILURE TO COMPLY with this notice within the stipulated time period will result in:\n"
        "- Immediate suspension of all benefits\n"
        "- Initiation of recovery proceedings for any amounts wrongfully claimed\n"
        "- Referral to appropriate law enforcement authorities"
    )
    
    pdf.multi_cell(0, 5, action_text)
    pdf.ln(5)
    
    # Signature Block
    pdf.set_font("Arial", 'B', 10)
    pdf.cell(0, 6, "Issued by Authority:", 0, 1)
    pdf.set_font("Arial", size=10)
    pdf.cell(0, 5, "Root Agent Fraud Detection System (AI-420)", 0, 1)
    pdf.cell(0, 5, "Digital Audit Division", 0, 1)
    pdf.cell(0, 5, "Ministry of Rural Development", 0, 1)
    
    # Save PDF
    os.makedirs(NOTICE_DIR, exist_ok=True)
    filename = os.path.join(NOTICE_DIR, f"Notice_{ben_id}.pdf")
    pdf.output(filename)
    print(f"   [OK] Generated Notice for {ben_id} - {name} [{risk_level}]")
    return filename


